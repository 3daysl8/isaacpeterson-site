// Eleventy builds /posts/*.md into /writing/<slug>/ and generates writing.html,
// posts.json and feed.xml. Every other page on the site is hand-written HTML and
// is copied through untouched: only .md and .njk are templates, so nothing in
// made/*/app (which contains {{ }}) is ever parsed.
import { feedPlugin } from "@11ty/eleventy-plugin-rss";
import markdownIt from "markdown-it";
import markdownItContainer from "markdown-it-container";

const SITE = "https://isaacpeterson.au";
const DEFAULT_IMAGE = "assets/hero-illustration.png";

// Frontmatter dates are parsed as UTC midnight, so every display uses UTC too.
// Local time would shift a post a day either side.
const isPublished = (post) => post.data.status === "published";
const stripSlash = (p) => (p || "").replace(/^\/+/, "");
const words = (html) => (html || "").replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;
const readTime = (html) => `${Math.max(1, Math.round(words(html) / 230))} min read`;

// One list for the writing page and posts.json: site posts plus the legacy
// off-site links in _data/external.json, newest first. Shape matches the
// original posts.json contract (tag, title, date YYYY-MM, readTime, url, image).
function feedEntries(posts, external) {
  const own = (posts || []).map((p) => ({
    sort: p.date.toISOString().slice(0, 10),
    tag: p.data.tag || "Writing",
    title: p.data.title,
    date: p.date.toISOString().slice(0, 7),
    readTime: readTime(p.content),
    url: p.url,
    image: stripSlash(p.data.image) || null,
  }));
  const ext = (external || []).map((e) => ({ sort: e.date, ...e }));
  return [...own, ...ext].sort((a, b) => b.sort.localeCompare(a.sort));
}

function markdown() {
  const md = markdownIt({ html: true, linkify: true, typographer: false });

  // ::: callout Optional title
  // Body in markdown.
  // :::
  md.use(markdownItContainer, "callout", {
    render(tokens, idx) {
      const t = tokens[idx];
      if (t.nesting !== 1) return "</aside>\n";
      const title = t.info.trim().replace(/^callout\s*/, "");
      return `<aside class="callout">${title ? `<p class="callout-title mono">${md.utils.escapeHtml(title)}</p>` : ""}\n`;
    },
  });

  // An image alone in its paragraph, with a title, becomes a captioned figure:
  //   ![alt text](/assets/posts/slug/shot.webp "Caption shown under it")
  md.core.ruler.push("figure", (state) => {
    const tk = state.tokens;
    for (let i = 0; i < tk.length - 2; i++) {
      const inline = tk[i + 1];
      if (tk[i].type !== "paragraph_open" || inline.type !== "inline") continue;
      const kids = inline.children || [];
      if (kids.length !== 1 || kids[0].type !== "image") continue;
      const title = kids[0].attrGet("title");
      if (!title) continue;
      kids[0].attrs = kids[0].attrs.filter(([k]) => k !== "title");
      const cap = new state.Token("html_inline", "", 0);
      cap.content = `<figcaption>${md.utils.escapeHtml(title)}</figcaption>`;
      kids.push(cap);
      tk[i].tag = "figure";
      tk[i + 2].tag = "figure";
    }
  });

  const image = md.renderer.rules.image;
  md.renderer.rules.image = (tokens, idx, opts, env, self) => {
    tokens[idx].attrSet("loading", "lazy");
    return image(tokens, idx, opts, env, self);
  };
  return md;
}

export default function (eleventyConfig) {
  eleventyConfig.setLibrary("md", markdown());

  // Hand-written site, copied as-is.
  for (const p of [
    "*.html", "*.css", "*.pdf", "made.json", "made", "assets",
    "favicon.ico", "apple-touch-icon.png", "_redirects", "_headers",
  ]) eleventyConfig.addPassthroughCopy(p);

  eleventyConfig.ignores.add("README.md");
  eleventyConfig.ignores.add("downloads-map.md");

  // Oldest first (Eleventy convention; the feed plugin reverses it).
  eleventyConfig.addCollection("publishedPosts", (api) =>
    api.getFilteredByGlob("posts/*.md").filter(isPublished).sort((a, b) => a.date - b.date));

  eleventyConfig.addFilter("feedEntries", feedEntries);
  eleventyConfig.addFilter("postsJson", (posts, external) =>
    JSON.stringify({
      _comment: "Generated by Eleventy at build time. Do not edit: site posts come from posts/*.md, off-site links from _data/external.json.",
      posts: feedEntries(posts, external).map(({ sort, ...e }) => e),
    }, null, 2));
  eleventyConfig.addFilter("readTime", readTime);
  eleventyConfig.addFilter("monthYear", (d) => {
    const [y, m] = String(d).split("-");
    return new Date(Date.UTC(+y, +m - 1, 1)).toLocaleDateString("en-AU", { month: "short", year: "numeric", timeZone: "UTC" });
  });
  eleventyConfig.addFilter("dateDisplay", (d) =>
    d.toLocaleDateString("en-AU", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" }));
  eleventyConfig.addFilter("isoDate", (d) => d.toISOString());
  eleventyConfig.addFilter("absUrl", (p) => `${SITE}/${stripSlash(p)}`);
  eleventyConfig.addFilter("ogImage", (p) => `${SITE}/${stripSlash(p) || DEFAULT_IMAGE}`);

  eleventyConfig.addPlugin(feedPlugin, {
    type: "atom",
    outputPath: "/feed.xml",
    collection: { name: "publishedPosts", limit: 20 },
    metadata: {
      language: "en-AU",
      title: "Isaac Peterson",
      subtitle: "Posts on workers comp, psychosocial risk, AI, and whatever I'm chewing on.",
      base: `${SITE}/`,
      author: { name: "Isaac Peterson" },
    },
  });

  return {
    templateFormats: ["md", "njk"],
    // Hub articles about n8n and templating contain {{ }}. Markdown is never run
    // through a template engine, so that text renders literally.
    markdownTemplateEngine: false,
    dir: { input: ".", includes: "_includes", data: "_data", output: "_site" },
  };
}
